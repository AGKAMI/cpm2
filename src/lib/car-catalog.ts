const BY_CODE = new Map(CAR_CATALOG.map((c) => [c.code, c]));

/** Exact code lookup. */
export function carByCode(code: number): CarEntry | undefined {
  return BY_CODE.get(code);
}

/** Search by code prefix OR name substring (case-insensitive). Type '49' or 'supra' -> TOYOTA SUPRA A80. */
export function searchCars(query: string, limit = 30): CarEntry[] {
  const q = query.trim().toLowerCase();
  if (!q) return CAR_CATALOG.slice(0, limit);
  const isNumeric = /^\d+$/.test(q);
  const hits = CAR_CATALOG.filter((c) =>
    isNumeric ? String(c.code).startsWith(q) : c.name.toLowerCase().includes(q),
  );
  return hits.slice(0, limit);
}
